-- Владелец объектов БД (логин для миграций)
CREATE ROLE app_owner LOGIN PASSWORD 'owner_password'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

-- Сервисные роли приложения
CREATE ROLE app_reader NOLOGIN
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

CREATE ROLE app_writer NOLOGIN
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

-- Роли для аудита
CREATE ROLE auditor NOLOGIN
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

CREATE ROLE audit_owner NOLOGIN
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

-- Административные роли
CREATE ROLE ddl_admin NOLOGIN
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

CREATE ROLE dml_admin NOLOGIN
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

-- Админ по ролям и привилегиям (NOLOGIN, управление через u_sec)
CREATE ROLE security_admin NOLOGIN
    NOSUPERUSER NOCREATEDB CREATEROLE NOREPLICATION NOBYPASSRLS;

-- Тестовые логин-роли
CREATE ROLE u_reader LOGIN PASSWORD 'reader_pass'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

CREATE ROLE u_writer LOGIN PASSWORD 'writer_pass'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

CREATE ROLE u_ddl LOGIN PASSWORD 'ddl_pass'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

CREATE ROLE u_dml LOGIN PASSWORD 'dml_pass'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

CREATE ROLE u_auditor LOGIN PASSWORD 'auditor_pass'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

CREATE ROLE u_sec LOGIN PASSWORD 'sec_pass'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

-- Выдача групповых прав тестовым пользователям
GRANT app_reader TO u_reader;
GRANT app_writer TO u_writer;
GRANT ddl_admin TO u_ddl;
GRANT dml_admin TO u_dml;
GRANT auditor TO u_auditor;
GRANT security_admin TO u_sec;

-- Фиксация search_path
ALTER ROLE u_reader  SET search_path = app, ref, pg_catalog;
ALTER ROLE u_writer  SET search_path = app, ref, stg, pg_catalog;
ALTER ROLE u_ddl     SET search_path = app, ref, stg, pg_catalog;
ALTER ROLE u_dml     SET search_path = app, ref, stg, pg_catalog;
ALTER ROLE u_auditor SET search_path = audit, pg_catalog;
ALTER ROLE u_sec     SET search_path = app, audit, pg_catalog;